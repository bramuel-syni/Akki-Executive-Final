async def _login(c, email, password):
    r = await c.post("/api/auth/login", json={"email": email, "password": password})
    assert r.status_code == 200, r.text
    body = r.json()
    return {"Authorization": f"Bearer {body.get('access_token') or body.get('token')}"}


async def test_chunk13_list_endpoint_returns_display_status_and_counts(client, db_conn, authed):
    """SV-04 list endpoint shape contract:
       • every row carries `display_status` ∈ DISPLAY_BUCKETS
       • response includes `status_counts` with keys
         {all, active, paused, complete, refused}
       • counts reflect ALL sessions in the context, NOT just the
         status-filter subset (Chunk 11 status_counts pattern)
    """
    headers = await _login(client, authed["email"], authed["password"])
    r = await client.get(
        f"/api/solva/v2/sessions?context_id={authed['context_id']}",
        headers=headers,
    )
    assert r.status_code == 200, r.text
    body = r.json()
    assert "items" in body and "status_counts" in body
    items = body["items"]
    counts = body["status_counts"]
    # Every item carries a display_status.
    for item in items:
        assert item.get("display_status") in DISPLAY_BUCKETS, item
    # Counts cover all four seeded buckets.
    assert counts["all"]      >= 4
    assert counts["active"]   >= 1
    assert counts["paused"]   >= 1
    assert counts["complete"] >= 1
    assert counts["refused"]  >= 1


async def test_chunk13_list_endpoint_status_filter_uses_display_buckets(client, db_conn, authed):
    """SV-04 — the `status` query param filters on the computed
    display_status bucket, NOT the raw stored status. Counts MUST be
    stable across filter toggles (taken pre-filter)."""
    headers = await _login(client, authed["email"], authed["password"])
    # Pull baseline counts.
    r = await client.get(
        f"/api/solva/v2/sessions?context_id={authed['context_id']}",
        headers=headers,
    )
    baseline_counts = r.json()["status_counts"]
    # Filter to PAUSED — should return only the paused session(s).
    r = await client.get(
        f"/api/solva/v2/sessions?context_id={authed['context_id']}&status=paused",
        headers=headers,
    )
    body = r.json()
    assert all(it["display_status"] == "paused" for it in body["items"])
    # Counts must match the unfiltered baseline.
    assert body["status_counts"] == baseline_counts


async def test_chunk13_read_only_enforced_on_complete_session(client, db_conn, authed):
    """SV-04 read-only enforcement: COMPLETE sessions reject answer
    submission with HTTP 409 (defence-in-depth; UI also hides the
    affordance via `solva-phase-d-read-only-banner`)."""
    headers = await _login(client, authed["email"], authed["password"])
    complete_sid = authed["session_ids"]["complete"]
    r = await client.post(
        f"/api/contexts/{authed['context_id']}/solva/v2/sessions/{complete_sid}/answer",
        headers=headers,
        json={"answer_text": "I should be blocked from submitting this."},
    )
    assert r.status_code == 409, r.text
    # Error message should mention the terminal state.
    err = r.json().get("detail", "")
    assert any(term in err.lower() for term in ("done", "complete", "no further"))


