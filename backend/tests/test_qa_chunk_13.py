async def test_chunk13_counts_honour_q_filter_but_not_status_filter(client, db_conn, authed):
    """The `q` filter SHOULD reduce counts; the status filter SHOULD NOT.

    This is the Chunk 11 `status_counts` rule applied to Solva. Together
    they preserve the tab-badge stability expected by the spec.
    """
    headers = await _login(client, authed["email"], authed["password"])

    # Baseline counts with no q, no status.
    r = await client.get(
        f"/api/solva/v2/sessions?context_id={authed['context_id']}",
        headers=headers,
    )
    base = r.json()["status_counts"]

    # Apply only a status filter — counts should NOT change.
    r = await client.get(
        f"/api/solva/v2/sessions?context_id={authed['context_id']}&status=active",
        headers=headers,
    )
    assert r.json()["status_counts"] == base

    # Apply a `q` that matches NO seed → counts should drop to zero.
    r = await client.get(
        f"/api/solva/v2/sessions?context_id={authed['context_id']}&q=zzz_nothing_will_match_xyz",
        headers=headers,
    )
    zero_counts = r.json()["status_counts"]
    assert zero_counts["all"] == 0


