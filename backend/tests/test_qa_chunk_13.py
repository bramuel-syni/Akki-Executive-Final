def _row(status=None, layer_state=None, hours_old=None, **extra):
    """Build a synthetic session row with `updated_at` `hours_old` ago."""
    row = {"status": status, "layer_state": layer_state, **extra}
    if hours_old is not None:
        ts = datetime.now(timezone.utc) - timedelta(hours=hours_old)
        row["updated_at"] = ts.isoformat()
    return row


def test_chunk13_classify_active_when_status_active_and_recent():
    assert classify(_row(status="active", hours_old=2)) == "active"


def test_chunk13_classify_paused_when_status_active_and_stale_24h():
    # Boundary: exactly PAUSE_THRESHOLD_HOURS old → PAUSED.
    assert classify(_row(status="active", hours_old=PAUSE_THRESHOLD_HOURS)) == "paused"


def test_chunk13_classify_paused_when_status_active_and_far_stale():
    assert classify(_row(status="active", hours_old=72)) == "paused"


def test_chunk13_classify_complete_when_status_completed():
    assert classify(_row(status="completed", hours_old=1)) == "complete"


def test_chunk13_classify_complete_when_layer_state_done():
    # Phase D writes layer_state="done" + status="completed" together;
    # either signal alone should still classify COMPLETE.
    assert classify(_row(status=None, layer_state="done", hours_old=1)) == "complete"


def test_chunk13_classify_refused_when_status_refused():
    assert classify(_row(status="refused", hours_old=1)) == "refused"


def test_chunk13_classify_refused_when_status_abandoned():
    # `abandoned` is the operator-driven session-closure path
    # (solva_phase_d.py:1334). Per spec the user-facing bucket is REFUSED.
    assert classify(_row(status="abandoned", hours_old=1)) == "refused"


def test_chunk13_classify_refused_when_layer_state_refused():
    # Guardrail hard-block path sets layer_state="refused" with
    # status="refused" but defends in depth.
    assert classify(_row(status=None, layer_state="refused")) == "refused"


def test_chunk13_classify_active_when_no_timestamps():
    # Drift-defensive default: an in-flight session with no updated_at
    # shouldn't render as PAUSED — claiming "≥24h since last interaction"
    # without a timestamp is a lie.
    assert classify({"status": "active"}) == "active"


def test_chunk13_classify_handles_datetime_object():
    # Phase D writes BSON datetime; list_sessions sometimes maps it
    # through `_iso_or_none`. Either shape must classify identically.
    dt_recent = datetime.now(timezone.utc) - timedelta(hours=3)
    assert classify({"status": "active", "updated_at": dt_recent}) == "active"
    dt_stale = datetime.now(timezone.utc) - timedelta(hours=48)
    assert classify({"status": "active", "updated_at": dt_stale}) == "paused"


def test_chunk13_classify_terminal_state_wins_over_recency():
    # A session marked refused but updated 2h ago is still REFUSED.
    assert classify(_row(status="refused", hours_old=2)) == "refused"


def test_chunk13_tally_groups_all_four_buckets_plus_all():
    rows = [
        _row(status="active",    hours_old=1),
        _row(status="active",    hours_old=2),
        _row(status="active",    hours_old=30),    # paused
        _row(status="completed", hours_old=1),
        _row(status="refused",   hours_old=1),
        _row(status="abandoned", hours_old=1),     # → refused
    ]
    counts = tally(rows)
    assert counts["all"]      == 6
    assert counts["active"]   == 2
    assert counts["paused"]   == 1
    assert counts["complete"] == 1
    assert counts["refused"]  == 2
    # Every bucket key is present even at zero count → keys stable.
    for bucket in DISPLAY_BUCKETS:
        assert bucket in counts


